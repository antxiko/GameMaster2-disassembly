# Los repartos con los que corre cada banco (tools/paginas.py, tools/bancos.py).
TRIOS = ((1, 2, 3), (1, 9, 10), (1, 5, 6), (1, 7, 8), (1, 4, None))


def trio(b):
    """El reparto con el que corre el codigo del banco b. El banco 0 corre con
    el de encendido, 1-2-3, salvo lo que cambien sus pasarelas."""
    if b == 0:
        return {0x6000: 1, 0x8000: 2, 0xA000: 3}
    for t in TRIOS:
        if b in t:
            return {v: n for v, n in zip((0x6000, 0x8000, 0xA000), t) if n is not None}
    return {}


