def _gemelas():
    """Los nombres repartidos a las copias (src/gemelas.txt, tools/gemelas.py)."""
    import os
    ruta = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "gemelas.txt")
    if not os.path.exists(ruta):
        return
    for ln in open(ruta, encoding="utf-8"):
        p = ln.split("#")[0].split(None, 3)
        if len(p) == 4 and (int(p[0][1:]), int(p[1], 16)) not in RUTINAS:
            RUTINAS[(int(p[0][1:]), int(p[1], 16))] = (p[2], p[3].strip())


